#!/usr/bin/env node
/**
 * Build step for NexDrive.
 *
 * The app ships as static files (no compile), so "building" means generating
 * the service worker's full precache list: scan public/ for cacheable assets
 * and write public/sw-precache.js (self.__PRECACHE_URLS = [...]). sw.js imports
 * it, so every shipped asset is cached for offline use on install — not only
 * the hand-listed CORE shell.
 */
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const PUBLIC = path.join(ROOT, 'public');

// Extensions worth precaching for offline. (Skip source maps and the SW files.)
const CACHE_EXT = new Set([
  '.html', '.js', '.css', '.json', '.webmanifest',
  '.svg', '.png', '.jpg', '.jpeg', '.webp', '.ico', '.woff2', '.woff',
]);
const SKIP_FILES = new Set(['sw.js', 'sw-precache.js']);

function* walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else yield full;
  }
}

function main() {
  if (!fs.existsSync(PUBLIC)) {
    console.error('build: missing public/ directory'); process.exit(1);
  }

  const urls = [];
  let bytes = 0;
  for (const file of walk(PUBLIC)) {
    const base = path.basename(file);
    if (SKIP_FILES.has(base)) continue;
    if (!CACHE_EXT.has(path.extname(file).toLowerCase())) continue;
    const rel = '/' + path.relative(PUBLIC, file).split(path.sep).join('/');
    urls.push(rel);
    bytes += fs.statSync(file).size;
  }
  urls.sort();

  const banner = '/* AUTO-GENERATED by build.js — do not edit. */\n';
  const body = 'self.__PRECACHE_URLS = ' + JSON.stringify(urls, null, 2) + ';\n';
  fs.writeFileSync(path.join(PUBLIC, 'sw-precache.js'), banner + body);

  const mb = (bytes / (1 << 20)).toFixed(1);
  console.log(`build: precache manifest written — ${urls.length} assets (${mb} MB) -> public/sw-precache.js`);
}

main();
